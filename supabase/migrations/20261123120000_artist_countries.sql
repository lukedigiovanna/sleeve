-- Retain unresolved values on the original, user-scoped artist row for review.
alter table public.artists add column legacy_country text;

with legacy as (
    select id, country as original,
           upper(regexp_replace(country, '^[[:space:]]+|[[:space:]]+$', '', 'g')) as code
    from public.artists
    where country is not null
),
normalized as (
    select legacy.id, legacy.original, country.code
    from legacy
    left join public.countries as country
      on country.code = case legacy.code when 'UK' then 'GB' else legacy.code end
)
update public.artists as artist
set country = normalized.code,
    legacy_country = case when normalized.code is null then normalized.original end
from normalized
where artist.id = normalized.id
  and artist.country is distinct from normalized.code;

alter table public.artists add constraint artists_country_fkey
    foreign key (country) references public.countries (code);
